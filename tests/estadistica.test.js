const assert=require('node:assert/strict');
const S=require('../estadistica.js');
const near=(a,b,t=1e-6)=>assert.ok(Math.abs(a-b)<t,`${a} != ${b}`);
near(S.quantile(.975),1.95996398454);
near(S.quantile(.975,24),2.0638985616);
near(S.quantile(.975,1),12.7062047364);
near(S.sf(2,24)*2,.0569398499366);
const t=S.infer({method:'t',confidence:.95,tail:'two',n:25,mean:52,sd:5,nullValue:50});
near(t.statistic,2);assert.equal(t.reject,false);
const z=S.infer({method:'z',confidence:.95,tail:'right',n:100,mean:53,sd:10,nullValue:50});
near(z.p,.001349898,1e-7);assert.equal(z.reject,true);
const left=S.infer({method:'z',confidence:.95,tail:'left',n:100,mean:47,sd:10,nullValue:50});near(left.p,z.p);
const prop=S.interval({method:'proportion',confidence:.95,n:10,success:0});assert.equal(prop.ci[0],0);near(prop.ci[1],.2775328);
assert.equal(S.sample({confidence:.95,parameter:'proportion',p:.5,error:.05,finite:false}).n,385);
assert.equal(S.sample({confidence:.95,parameter:'proportion',p:.5,error:.05,finite:true,population:1000}).n,278);
near(S.summary([1,2,3]).sd,1);assert.equal(S.summary([1,2,3]).n,3);
assert.throws(()=>S.infer({method:'t',confidence:.95,tail:'two',n:1,mean:52,sd:5,nullValue:50}));
assert.throws(()=>S.interval({method:'proportion',confidence:.95,n:10,success:11}));
assert.throws(()=>S.sample({confidence:.95,parameter:'proportion',p:.5,error:0,finite:false}));
console.log('Pruebas de regresión estadísticas: OK');
